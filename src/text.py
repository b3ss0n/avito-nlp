"""Нормализация текста для лексического поиска (BM25).

Пайплайн: lowercase -> ё->е -> токены по регулярке -> стемминг -> стоп-слова.
Одна и та же функция применяется и к запросам, и к объявлениям, иначе
токены не совпадут ("монтажа" в объявлении и "монтаж" в запросе).

Стемминг выбран вместо лемматизации ради скорости: корпус ~500k объявлений
с длинными описаниями. Для поиска не важно, что стем - не настоящее слово,
важно только, чтобы разные формы одного слова давали одинаковый токен.
"""

import re
from functools import lru_cache

import snowballstemmer

# Слово = последовательность русских/латинских букв или цифр.
# Пунктуация, эмодзи, "●" и т.п. просто не попадают в токены.
TOKEN_RE = re.compile(r"[a-zа-я0-9]+")

_ru_stemmer = snowballstemmer.stemmer("russian")
_en_stemmer = snowballstemmer.stemmer("english")

# Короткий список служебных слов. Большую часть "мусора" BM25 и так гасит
# через IDF, поэтому список намеренно маленький: выкидываем только
# предлоги/союзы/частицы, которые точно не несут смысла услуги.
STOP_WORDS = {
    "и", "в", "во", "на", "с", "со", "по", "для", "от", "до", "из", "к", "ко",
    "за", "о", "об", "у", "а", "но", "или", "не", "же", "ли", "бы", "то",
    "что", "как", "так", "это", "мы", "вы", "я", "ваш", "наш", "все", "весь",
}


@lru_cache(maxsize=1_000_000)
def stem_word(word: str) -> str:
    """Стем одного слова с кэшем.

    Уникальных слов в корпусе на порядки меньше, чем словоупотреблений,
    поэтому кэш ускоряет нормализацию в разы.
    """
    if word.isascii():
        return _en_stemmer.stemWord(word)
    return _ru_stemmer.stemWord(word)


def tokenize(text: str | None) -> list[str]:
    """Текст -> список нормализованных токенов."""
    if not text:
        return []
    text = text.lower().replace("ё", "е")
    tokens = []
    for word in TOKEN_RE.findall(text):
        # однобуквенные токены ("м", "г", "5") почти всегда шум
        if len(word) < 2 or word in STOP_WORDS:
            continue
        tokens.append(stem_word(word))
    return tokens


def normalize(text: str | None) -> str:
    """То же, что tokenize, но строкой через пробел (удобно хранить в parquet)."""
    return " ".join(tokenize(text))
